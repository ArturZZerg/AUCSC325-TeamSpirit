import { Prisma } from '@prisma/client';
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const directory = new URL('apps/api/prisma/migrations/', root);
const types = { String: 'text', Int: 'int4', Boolean: 'bool', DateTime: 'timestamp', Json: 'jsonb' };
const natives = { Uuid: 'uuid' };
const tables = Prisma.dmmf.datamodel.models.map(model => ({
  name: model.dbName ?? model.name,
  columns: model.fields.filter(field => field.kind !== 'object').map(field => {
    const type = field.nativeType ? natives[field.nativeType[0]] : types[field.type];
    if (!type) throw new Error(`Extend readiness type mapping for ${model.name}.${field.name}`);
    return [field.dbName ?? field.name, field.isList ? `_${type}` : type, field.isRequired ? 'NO' : 'YES'];
  }),
}));
const migrations = [];
for (const name of (await readdir(directory, { withFileTypes: true })).filter(entry => entry.isDirectory()).map(entry => entry.name).sort()) {
  const sql = await readFile(new URL(`${name}/migration.sql`, directory));
  // Prisma accepts both platform line endings. Keep checksums portable.
  const checksums = [...new Set([sql.toString().replace(/\r\n/g, '\n'), sql.toString().replace(/\r?\n/g, '\r\n')])]
    .map(text => createHash('sha256').update(text).digest('hex'));
  migrations.push({ name, checksums });
}
const target = new URL('apps/api/src/schema-manifest.ts', root);
const schemaHash = createHash('sha256').update((await readFile(new URL('apps/api/prisma/schema.prisma', root), 'utf8')).replace(/\r\n/g, '\n')).digest('hex');
// Prisma formats its generated copy. Compare tokens while preserving strings;
// whitespace and comments alone do not change the client contract.
const tokens = text => (text.match(/"(?:\\.|[^"\\])*"|\/\/[^\r\n]*|\/\*[\s\S]*?\*\/|\s+|[^\s]/g) ?? [])
  .filter(token => !/^\s+$/.test(token) && !token.startsWith('//') && !token.startsWith('/*')).join('');
if (tokens(await readFile(new URL('node_modules/.prisma/client/schema.prisma', root), 'utf8')) !==
  tokens(await readFile(new URL('apps/api/prisma/schema.prisma', root), 'utf8')))
  throw new Error('Generated Prisma client is stale. Run db:generate before schema:manifest.');
const tableText = tables.map(table => `    { name: ${JSON.stringify(table.name)}, columns: [\n${table.columns.map(column => `      ${JSON.stringify(column)},`).join('\n')}\n    ] },`).join('\n');
const output = `// Generated by npm run schema:manifest after db:generate. Do not edit.\nexport const requiredSchema = {\n  schemaHash: '${schemaHash}',\n  tables: [\n${tableText}\n  ],\n  migrations: ${JSON.stringify(migrations, null, 2)},\n} as const;\n`;
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replace(/\r\n/g, '\n') !== output) throw new Error('Readiness schema manifest is stale. Run db:generate then schema:manifest.');
  console.log('Readiness schema manifest matches generated Prisma client and migrations');
} else { await writeFile(target, output); console.log(`Generated ${fileURLToPath(target)}`); }
