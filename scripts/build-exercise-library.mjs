// Builds the exercise library (ADR 022) from free-exercise-db (Unlicense):
//   node scripts/build-exercise-library.mjs path/to/free-exercise-db/dist/exercises.json
// Writes the slim app index to packages/domain and the instructions to the API.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const source = process.argv[2];
if (!source) { console.error('Usage: node scripts/build-exercise-library.mjs <exercises.json>'); process.exit(1); }

const muscles = { abdominals: 'core', abductors: 'glutes', adductors: 'adductors', biceps: 'biceps', calves: 'calves', chest: 'chest',
  forearms: 'forearms', glutes: 'glutes', hamstrings: 'hamstrings', lats: 'back', 'lower back': 'back', 'middle back': 'back',
  neck: 'traps', quadriceps: 'quads', shoulders: 'shoulders', traps: 'traps', triceps: 'triceps' };
const equipment = { barbell: 'barbell', 'e-z curl bar': 'barbell', dumbbell: 'dumbbell', machine: 'machine', cable: 'cable',
  'body only': 'bodyweight', kettlebells: 'kettlebell', bands: 'band' };
const map = (values, table) => [...new Set(values.map(value => table[value]).filter(Boolean))];

const rows = JSON.parse(readFileSync(source, 'utf8'))
  .filter(item => /^[A-Za-z0-9_-]+$/.test(item.id) && item.name && item.images?.length >= 1)
  .sort((a, b) => a.id.localeCompare(b.id));
const library = rows.map(item => {
  const primary = map(item.primaryMuscles ?? [], muscles);
  const secondary = map(item.secondaryMuscles ?? [], muscles).filter(muscle => !primary.includes(muscle));
  return [item.id, item.name.trim(), equipment[item.equipment] ?? 'other', item.level ?? 'beginner', item.category ?? 'strength', primary, secondary, item.images.length];
});
const header = '// Generated by scripts/build-exercise-library.mjs from free-exercise-db (Unlicense). Do not edit.\n'
  + '// [id, name, equipment, level, category, primary muscles, secondary muscles, photo count]\n';
writeFileSync(new URL('packages/domain/src/exercise-library-data.ts', root),
  `${header}export const exerciseLibraryRows = ${JSON.stringify(library)} as const;\n`);
writeFileSync(new URL('apps/api/data/exercise-instructions.json', root),
  JSON.stringify(Object.fromEntries(rows.map(item => [item.id, (item.instructions ?? []).map(text => text.trim()).filter(Boolean)]))));
console.log(`Wrote ${library.length} exercises to ${fileURLToPath(new URL('packages/domain/src/exercise-library-data.ts', root))}`);
